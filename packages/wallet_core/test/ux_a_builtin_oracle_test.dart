void main() {
  test('there are 89 per-brand rules and every one is hit by a sample', () {
    expect(builtInRules, hasLength(89));
    final cz = Categorizer();
    for (final r in builtInRules) {
      expect(_samples.any((s) => r.re.hasMatch(s.toLowerCase().trim())), isTrue, reason: r.slug);
    }
    expect(cz.merchantCategory('pos lidl'), 'Groceries');
  });

  test('every sample gets the category the grouped rules gave it', () {
    final cz = Categorizer();
    for (final s in _samples) {
      expect(cz.merchantCategory(s), _oldCategory(s), reason: s);
    }
  });
}
